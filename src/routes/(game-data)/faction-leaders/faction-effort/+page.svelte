<script lang="ts">
	import * as Card from '$lib/components/ui/card';
	import * as Table from '$lib/components/ui/table';
	import { factionNames, formatDate } from '$lib/shared';

	let { data } = $props();
	let title = $derived(data.title);
	let factionEfforts = $derived(data.factionEfforts);
	let timeRange = $derived.by(() => {
		let { fromDate, toDate } = factionEfforts.results[0];
		return `${formatDate(fromDate, true)} to ${formatDate(toDate, true)}`;
	});
</script>

<h1>{title}</h1>

<p>View effort generated by leaders for each faction.</p>

<div class="flex gap-2 flex-col sm:flex-row flex-wrap my-4">
	<div class="flex gap-2 flex-col w-full sm:w-fit">
		<!-- Effort Totals -->
		<Card.Root>
			<Card.Content>
				<h3 class="mt-0!">Effort Totals</h3>
				<p>From {timeRange}.</p>
				<Table.Root class="mt-2">
					<Table.Header>
						<Table.Row>
							<Table.Head class="px-2 min-w-34">Faction</Table.Head>
							<Table.Head class="px-2 text-right">Top Effort</Table.Head>
							<Table.Head class="px-2 min-w-18 text-right">Effort</Table.Head>
						</Table.Row>
					</Table.Header>
					<Table.Body>
						{#each factionEfforts.results as row}
							<Table.Row>
								<Table.Cell class="p-2">{factionNames[row.factionId]}</Table.Cell>
								<Table.Cell class="p-2 text-right">{row.topEffort.toLocaleString()}</Table.Cell>
								<Table.Cell class="p-2 text-right">{row.effort.toLocaleString()}</Table.Cell>
							</Table.Row>
						{/each}
					</Table.Body>
				</Table.Root>
			</Card.Content>
		</Card.Root>
	</div>
</div>
